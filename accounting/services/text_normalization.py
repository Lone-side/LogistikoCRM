# -*- coding: utf-8 -*-
"""
accounting/services/text_normalization.py

Κανονικοποίηση ελληνικού κειμένου για αναζήτηση σε έγγραφα.

Το πρόβλημα: η εξαγωγή κειμένου από PDF/OCR δεν παράγει πάντα τους
πραγματικούς ελληνικούς χαρακτήρες. Δύο επιβεβαιωμένες περιπτώσεις:

1. «∆» U+2206 INCREMENT (μαθηματικό σύμβολο) αντί για «Δ» U+0394 GREEK
   CAPITAL LETTER DELTA. Πολλά PDF fonts κάνουν map το κεφαλαίο δέλτα
   στο INCREMENT, οπότε το «∆ΟΚΙΜΩΝ» δεν βρίσκεται με αναζήτηση «ΔΟΚΙΜΩΝ».
2. Λατινικοί σωσίες: «ΦΠA» με λατινικό A (U+0041) αντί για ελληνικό
   Α (U+0391). Το ίδιο για B, E, Z, H, I, K, M, N, O, P, T, X, Y.

Η λύση είναι συμμετρική: το `extracted_text` αποθηκεύεται κανονικοποιημένο
(είναι πεδίο αναζήτησης — δεν εμφανίζεται πουθενά σε UI/API) και ο όρος
αναζήτησης κανονικοποιείται με την ίδια συνάρτηση πριν το ταίριασμα.
Έτσι δεν χρειάζεται συνδυαστική παραγωγή παραλλαγών του όρου.

Η κανονικοποίηση είναι: αφαίρεση τόνων → κεφαλαία (το τελικό «ς» γίνεται
«Σ») → χαρτογράφηση σωσιών σε ελληνικά.
"""
import unicodedata

# Χαρακτήρες που η εξαγωγή PDF/OCR παράγει αντί για τους ελληνικούς.
# Η κατεύθυνση είναι «προς τα ελληνικά» επειδή τα έγγραφα είναι ελληνικά·
# η επιλογή κατεύθυνσης δεν έχει σημασία για την ορθότητα εφόσον
# εφαρμόζεται και στις δύο πλευρές της σύγκρισης.
CONFUSABLES = {
    # Μαθηματικά/τεχνικά σύμβολα που χρησιμοποιούνται ως ελληνικά γράμματα
    '∆': 'Δ',  # ∆ INCREMENT            → Δ
    'Ω': 'Ω',  # Ω OHM SIGN             → Ω
    '∑': 'Σ',  # ∑ N-ARY SUMMATION      → Σ
    '∏': 'Π',  # ∏ N-ARY PRODUCT        → Π
    # Λατινικά κεφαλαία με ελληνικό οπτικό σωσία
    'A': 'Α', 'B': 'Β', 'E': 'Ε', 'Z': 'Ζ',
    'H': 'Η', 'I': 'Ι', 'K': 'Κ', 'M': 'Μ',
    'N': 'Ν', 'O': 'Ο', 'P': 'Ρ', 'T': 'Τ',
    'X': 'Χ', 'Y': 'Υ',
    # Κυριλλικά κεφαλαία με ελληνικό οπτικό σωσία (σπανιότερα, από OCR)
    'А': 'Α', 'В': 'Β', 'Е': 'Ε',
    'К': 'Κ', 'М': 'Μ', 'Н': 'Ν',
    'О': 'Ο', 'Р': 'Ρ', 'С': 'Σ',
    'Т': 'Τ', 'Х': 'Χ',
}

_CONFUSABLE_TABLE = str.maketrans(CONFUSABLES)


def strip_accents(text):
    """Αφαιρεί τόνους/διακριτικά (NFD → πέταμα combining marks)."""
    decomposed = unicodedata.normalize('NFD', text or '')
    return ''.join(c for c in decomposed if not unicodedata.combining(c))


def normalize_search_text(text):
    """
    Κανονική μορφή για αναζήτηση: χωρίς τόνους, κεφαλαία, με τους
    οπτικούς σωσίες χαρτογραφημένους σε ελληνικούς χαρακτήρες.

    Ίδιο αποτέλεσμα για «Δήλωση», «δηλωση», «∆ΗΛΩΣΗ» και «ΔHΛΩΣH».
    """
    if not text:
        return ''
    return strip_accents(text).upper().translate(_CONFUSABLE_TABLE)
